# راهنمای بایگانی

## ساختار بایگانی
بایگانی شرکت‌ها شامل چهار سطح است: ۰۱ - رشد مقدماتی، ۰۲ - رشد، ۰۳ - پارکی، ۰۴ - خروج‌یافته.
هر شرکت در یکی از این سطوح، در پوشه‌ای با نام خود قرار می‌گیرد.

## قانون نام‌گذاری
هر سند با این الگو نام‌گذاری می‌شود:
[نوع سند] [موضوع] [سال] [نام شرکت].[فرمت]
مثال: قرارداد استقرار 1404 اوان.pdf
در صورت وجود بیش از یک نسخه: قرارداد استقرار 1404 اوان نسخه 02.pdf

## ثبت سند جدید
۱. شرکت موردنظر را از درخت سمت چپ انتخاب کنید.
۲. روی «+ ثبت سند جدید» کلیک کنید.
۳. فایل را انتخاب کنید و فیلدهای نوع سند، موضوع، سال و در صورت نیاز نسخه را تکمیل کنید.
۴. نام تولیدشده را بررسی و روی «ثبت در بایگانی» کلیک کنید.

## جستجو
از کادر جستجوی سریع در بالای صفحه برای یافتن اسناد در تمام شرکت‌ها استفاده کنید — نیازی به باز کردن تک‌تک پوشه‌ها نیست.

## قانون طلایی
هرگز فایلی را مستقیماً در ویندوز جابه‌جا یا تغییرنام ندهید — همیشه از این برنامه استفاده کنید تا پایگاه داده با بایگانی هماهنگ بماند.
